def token() -> str:
    value = os.environ.get("CLICKUP_API_KEY") or os.environ.get("CLICKUP_API_TOKEN")
    if not value:
        sys.exit(
            "Missing ClickUp token. Export CLICKUP_API_KEY in this shell "
            "(you already have it in ~/.zshrc — open a new terminal or run: source ~/.zshrc)."
        )
    return value


def api_get(path: str, params: dict | None = None, retries: int = 4) -> object:
    url = f"{API_BASE}{path}"
    if params:
        url += "?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(
        url,
        headers={
            "Authorization": token(),
            "Accept": "application/json",
        },
    )
    last_error: Exception | None = None
    for attempt in range(retries):
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                return json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as exc:
            body = exc.read().decode("utf-8", errors="replace")
            last_error = exc
            if exc.code in {429, 500, 502, 503, 504} and attempt < retries - 1:
                wait = 1.5 * (attempt + 1)
                print(f"  retry {path} after {exc.code} ({wait:.1f}s)")
                time.sleep(wait)
                continue
            raise RuntimeError(f"ClickUp API {exc.code} for {path}: {body[:500]}") from exc
        except urllib.error.URLError as exc:
            last_error = exc
            if attempt < retries - 1:
                wait = 1.5 * (attempt + 1)
                print(f"  retry {path} after network error ({wait:.1f}s)")
                time.sleep(wait)
                continue
            raise RuntimeError(f"ClickUp API network error for {path}: {exc}") from exc
    raise RuntimeError(f"ClickUp API failed for {path}: {last_error}")


def slugify(name: str) -> str:
    text = name.strip().lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    text = re.sub(r"-{2,}", "-", text).strip("-")
    return text or "page"


def ms_to_iso(value: object) -> str | None:
    if not value:
        return None
    try:
        ts = int(value)
    except (TypeError, ValueError):
        return None
    if ts > 10_000_000_000:
        ts /= 1000
    return datetime.fromtimestamp(ts, tz=timezone.utc).strftime("%Y-%m-%d")


def collect_nodes(pages: list) -> list[dict]:
    found: list[dict] = []

    def walk(nodes: list) -> None:
        for node in nodes:
            if not isinstance(node, dict):
                continue
            found.append(node)
            walk(node.get("pages") or [])

    walk(pages)
    return found


def prune(pages: list[dict]) -> list[dict]:
    kept = []
    for page in pages:
        if page.get("deleted") or page.get("archived"):
            continue
        page["pages"] = prune(page.get("pages") or [])
        kept.append(page)
    return kept


def build_tree(pages: list[dict]) -> list[dict]:
    """Return top-level pages, attaching children via `pages` when the API is flat."""
    if any(page.get("pages") for page in pages):
        return pages

    by_id = {page["id"]: page for page in pages if page.get("id")}
    for page in by_id.values():
        page["pages"] = []
    roots: list[dict] = []
    for page in by_id.values():
        parent = page.get("parent_page_id")
        if parent and parent in by_id:
            by_id[parent]["pages"].append(page)
        else:
            roots.append(page)
    return roots


def unique_slug(name: str, used: set[str]) -> str:
    base = slugify(name)
    slug = base
    n = 2
    while slug in used:
        slug = f"{base}-{n}"
        n += 1
    used.add(slug)
    return slug


def assign_paths(roots: list[dict]) -> Path:
    """Give every page a folder. Root index.html is reserved for the keeper page.

    Returns the folder of the Doc's first top-level page, used as the Doc's local home.
    """
    top_slugs: set[str] = {"assets", "index"} | set(TOP_LEVEL_PATHS.values())

    def assign(page: dict, rel: Path, child_slugs: set[str]) -> None:
        page["_rel"] = rel
        page["_file"] = rel / "index.html"
        override = PAGE_TITLES.get(site_key(rel))
        if override:
            page["name"] = override
        next_used: set[str] = set()
        for child in page.get("pages") or []:
            child_slug = unique_slug(child.get("name") or "page", child_slugs)
            assign(child, rel / child_slug, next_used)

    for page in roots:
        name = page.get("name") or "page"
        target = TOP_LEVEL_PATHS.get(slugify(name))
        rel = Path(target) if target else Path(unique_slug(name, top_slugs))
        assign(page, rel, set())

    return roots[0]["_rel"]


def rel_href(from_rel: Path, to_rel: Path) -> str:
    start = Path(".") if from_rel == Path(".") else from_rel
    target = Path(".") if to_rel == Path(".") else to_rel
    href = os.path.relpath(target, start)
    if href == ".":
        return "index.html"
    return href.rstrip("/") + "/"


def page_url_ids(url: str) -> list[str]:
    parsed = urllib.parse.urlparse(url)
    if "clickup.com" not in parsed.netloc:
        return []
    parts = [p for p in parsed.path.split("/") if p]
    return parts


def rewrite_clickup_href(url: str, page: dict, by_id: dict[str, dict], doc_home: Path) -> str:
    if not url or url.startswith("#") or url.startswith("mailto:"):
        return url
    parsed = urllib.parse.urlsplit(url)
    if "clickup.com" not in parsed.netloc:
        return url
    for part in reversed(page_url_ids(url)):
        if part in by_id:
            return rel_href(page["_rel"], by_id[part]["_rel"])
    if DOC_ID in url:
        return rel_href(page["_rel"], doc_home)
    return url


def download_image(url: str, assets: Path, cache: dict[str, str]) -> str | None:
    if url in cache:
        return cache[url]
    if url.startswith("data:") or url.startswith("#"):
        return None
    parsed = urllib.parse.urlsplit(url)
    if parsed.scheme not in {"http", "https"}:
        return None
    ext = Path(parsed.path).suffix.lower()
    if ext not in {".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg", ".avif"}:
        ext = ".png"
    digest = hashlib.sha256(url.encode()).hexdigest()[:16]
    filename = f"{digest}{ext}"
    dest = assets / filename
    if not dest.exists():
        headers = {"User-Agent": "fantasy-fucks-clickup-export/1.0"}
        if CLICKUP_HOST_RE.match(url) or "clickup.com" in parsed.netloc:
            headers["Authorization"] = token()
        req = urllib.request.Request(url, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                dest.write_bytes(resp.read())
        except (urllib.error.URLError, urllib.error.HTTPError) as exc:
            print(f"  skip image {url}: {exc}")
            return None
    cache[url] = filename
    return filename


def asset_href(page: dict, filename: str) -> str:
    assets_rel = Path("assets") / filename
    start = Path(".") if page["_rel"] == Path(".") else page["_rel"]
    return os.path.relpath(assets_rel, start)


def localize_images(text: str, page: dict, assets: Path, cache: dict[str, str]) -> str:
    def replace_md(match: re.Match) -> str:
        alt, url = match.group(1), match.group(2)
        name = download_image(url, assets, cache)
        if not name:
            return match.group(0)
        return f"![{alt}]({asset_href(page, name)})"

    def replace_html(match: re.Match) -> str:
        url = match.group(2)
        name = download_image(url, assets, cache)
        if not name:
            return match.group(0)
        return f"{match.group(1)}{asset_href(page, name)}{match.group(3)}"

    text = IMG_MD_RE.sub(replace_md, text)
    text = IMG_HTML_RE.sub(replace_html, text)
    return text


def rewrite_markdown_links(text: str, page: dict, by_id: dict[str, dict], doc_home: Path) -> str:
    def repl(match: re.Match) -> str:
        label, url = match.group(1), match.group(2)
        return f"[{label}]({rewrite_clickup_href(url, page, by_id, doc_home)})"

    return MD_LINK_RE.sub(repl, text)


