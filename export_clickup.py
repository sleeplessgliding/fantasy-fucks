def esc(value: object) -> str:
    return (
        str(value or "")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def fetch_pages() -> list[dict]:
    payload = api_get(
        f"/workspaces/{WORKSPACE_ID}/docs/{DOC_ID}/pages",
        {"max_page_depth": "-1", "content_format": "text/md"},
    )
    if isinstance(payload, dict):
        pages = payload.get("pages") or payload.get("data") or []
        if isinstance(pages, dict):
            pages = [pages]
    elif isinstance(payload, list):
        pages = payload
    else:
        sys.exit(f"Unexpected pages payload: {type(payload)}")

    nodes = collect_nodes(pages)
    for node in nodes:
        if node.get("deleted") or node.get("archived"):
            continue
        if node.get("content"):
            continue
        time.sleep(0.15)
        detail = api_get(
            f"/workspaces/{WORKSPACE_ID}/docs/{DOC_ID}/pages/{node['id']}",
            {"content_format": "text/md"},
        )
        if isinstance(detail, dict) and detail.get("content"):
            node["content"] = detail["content"]
            node.setdefault("sub_title", detail.get("sub_title"))
            node.setdefault("date_updated", detail.get("date_updated"))
            if detail.get("cover"):
                node["cover"] = detail["cover"]
    return prune(pages)


NAV_FILE = "nav.json"
CHROME_MARKER = "<!-- site-chrome -->"
CHILDREN_RE = re.compile(r'<nav class="children">.*?</nav>', re.S)
CHILD_LINK_RE = re.compile(r'<li><a href="([^"]+)">(.*?)</a></li>', re.S)
H1_RE = re.compile(r"<h1[^>]*>(.*?)</h1>", re.S)
OLD_HEADER_RE = re.compile(r'<header class="site">.*?</header>\s*', re.S)
CHROME_RE = re.compile(r'<aside class="sidebar".*?</header>', re.S)


def nav_from_pages(roots: list[dict]) -> list[dict]:
    """Nav tree for the sidebar, nested by output folder rather than ClickUp parentage."""
    nodes = [
        {
            "label": page.get("name") or "Page",
            "href": site_key(page["_rel"]),
            "children": [],
        }
        for page in collect_nodes(roots)
    ]
    by_href = {node["href"]: node for node in nodes}

    tree: list[dict] = []
    for node in nodes:
        parent = None
        for href, candidate in by_href.items():
            if candidate is node or not href.endswith("/"):
                continue
            if node["href"].startswith(href) and (parent is None or len(href) > len(parent["href"])):
                parent = candidate
        (parent["children"] if parent else tree).append(node)

    extra = [
        {"label": "2026 Draft and Keeper Info", "href": "index.html", "children": []},
        {"label": "2026 Keepers", "href": "2026-keepers/", "children": []},
    ]
    skip = {item["href"] for item in extra}
    tree = [node for node in tree if node["href"] not in skip]
    rules = next((node for node in tree if node["href"] == "rules/"), None)
    if rules is None:
        rules = {"label": "Rules", "href": "rules/", "children": []}
        tree.append(rules)
    have = {child["href"] for child in rules["children"]}
    for item in reversed(extra):
        if item["href"] not in have:
            rules["children"].insert(0, item)

    def reorder(nodes: list[dict], parent_href: str) -> None:
        pinned = NAV_FIRST.get(parent_href, ())
        nodes.sort(key=lambda n: pinned.index(n["href"]) if n["href"] in pinned else len(pinned))
        for node in nodes:
            reorder(node["children"], node["href"])

    for node in tree:
        reorder(node["children"], node["href"])

    order = {target: i for i, (_, target) in enumerate(SITE_NAV)}
    tree.sort(key=lambda n: order.get(n["href"], len(order)))

    for item in tree:
        for label, target in SITE_NAV:
            if item["href"] == target:
                item["label"] = label
    return tree


def nav_from_disk(root: Path) -> list[dict]:
    """Rebuild the nav tree from exported HTML, using each page's child list for ordering."""

    def read(rel: Path) -> tuple[str, list[tuple[str, str]]]:
        path = root / rel / "index.html" if rel != Path(".") else root / "index.html"
        text = path.read_text(encoding="utf-8", errors="replace")
        heading = H1_RE.search(text)
        label = html_lib.unescape(heading.group(1).strip()) if heading else rel.name
        block = CHILDREN_RE.search(text)
        kids = []
        if block:
            for href, raw in CHILD_LINK_RE.findall(block.group(0)):
                kids.append((href.strip("/"), html_lib.unescape(raw.strip())))
        return label, kids

    def node(rel: Path) -> dict:
        label, kids = read(rel)
        return {
            "label": label,
            "href": site_key(rel),
            "children": [node(rel / slug) for slug, _ in kids],
        }

    tree = []
    for label, target in SITE_NAV:
        if target.endswith(".html"):
            tree.append({"label": label, "href": target, "children": []})
            continue
        rel = Path(target.rstrip("/"))
        if (root / rel / "index.html").exists():
            item = node(rel)
            item["label"] = label
            tree.append(item)
    return tree


def load_nav(root: Path) -> list[dict]:
    path = root / NAV_FILE
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    tree = nav_from_disk(root)
    path.write_text(json.dumps(tree, indent=2), encoding="utf-8")
    print(f"Built {NAV_FILE} from exported pages")
    return tree


