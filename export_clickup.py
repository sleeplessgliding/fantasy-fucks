def nav_label(tree: list[dict], href: str) -> str | None:
    for node in tree:
        if node["href"] == href:
            return node["label"]
        found = nav_label(node.get("children") or [], href)
        if found:
            return found
    return None


def patch_chrome(root: Path, tree: list[dict], site_name: str = "Fantasy Fucks") -> None:
    """Swap the sidebar/topbar on already-exported pages without re-fetching ClickUp."""
    targets: list[tuple[Path, str]] = []
    for path in sorted(root.rglob("index.html")):
        if any(part.startswith(".") for part in path.relative_to(root).parts):
            continue
        targets.append((path, site_key(path.parent.relative_to(root))))

    updated = 0
    for path, current in targets:
        text = path.read_text(encoding="utf-8")
        is_export = "clickup-export:" in text
        if not is_export and CHROME_MARKER not in text and not CHROME_RE.search(text):
            continue
        rel = path.parent.relative_to(root)
        heading = H1_RE.search(text)
        heading_text = html_lib.unescape(heading.group(1).strip()) if heading else ""
        title = (heading_text if is_export else "") or nav_label(tree, current) or site_name
        chrome = site_chrome(rel, tree, site_name, title, current)

        if CHROME_RE.search(text):
            patched = CHROME_RE.sub(lambda _: chrome, text, count=1)
        elif CHROME_MARKER in text:
            patched = text.replace(CHROME_MARKER, chrome, 1)
        elif OLD_HEADER_RE.search(text):
            patched = OLD_HEADER_RE.sub(
                lambda _: f'<a class="skip-link" href="#main">Skip to content</a>\n'
                f'<div class="shell">\n{chrome}\n',
                text,
                count=1,
            )
            patched = patched.replace("<main>", '<main class="page" id="main">', 1)
            patched = patched.replace(
                "</main>\n<footer class=\"site\">",
                '</main>\n<footer class="site">',
                1,
            )
            patched = patched.replace(
                "</footer>\n</body>",
                f'</footer>\n</div>\n</div>\n<div class="scrim"></div>\n'
                f'<script src="{href_from(rel, "site.js")}"></script>\n</body>',
                1,
            )
            patched = patched.replace(
                '<meta name="viewport" content="width=device-width, initial-scale=1">',
                '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
                '<meta name="color-scheme" content="dark light">',
                1,
            )
            patched = patched.replace("</head>", f"{HEAD_SCRIPT}\n</head>", 1)
        else:
            continue

        if patched != text:
            path.write_text(patched, encoding="utf-8")
            updated += 1
    print(f"Updated chrome on {updated} page(s)")


def write_site(root: Path, dry_run: bool) -> None:
    print(f"Fetching ClickUp Doc {DOC_ID}…")
    site_name = "Fantasy Fucks"
    try:
        doc = api_get(f"/workspaces/{WORKSPACE_ID}/docs/{DOC_ID}")
        if isinstance(doc, dict) and doc.get("name"):
            site_name = doc["name"]
    except RuntimeError as exc:
        print(f"  skipping doc metadata ({exc})")
    roots = build_tree(fetch_pages())
    if not roots:
        sys.exit("No pages returned for this Doc.")
    doc_home = assign_paths(roots)
    nodes = collect_nodes(roots)
    by_id = {page["id"]: page for page in nodes if page.get("id")}

    print(f"{len(nodes)} page(s):")
    for page in nodes:
        print(f"  {page['_file']}  ←  {page.get('name')}")

    if dry_run:
        return

    tree = nav_from_pages(roots)
    assets = root / "assets"
    assets.mkdir(exist_ok=True)
    write_shared_assets(root, tree)
    cache: dict[str, str] = {}

    for page in nodes:
        cover = (page.get("cover") or {}).get("image_url")
        body = page.get("content") or ""
        if cover:
            name = download_image(cover, assets, cache)
            if name:
                body = f"![cover]({asset_href(page, name)})\n\n" + body
        body = localize_images(body, page, assets, cache)
        body = rewrite_markdown_links(body, page, by_id, doc_home)
        html = rewrite_html_hrefs(md_to_html(body), page, by_id, doc_home)
        html = localize_images(html, page, assets, cache)
        page["_html"] = html

        dest = root / page["_file"]
        if dest.relative_to(root).as_posix() in PROTECTED:
            print(f"  skip protected {dest}")
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(render_page(page, by_id, site_name, tree), encoding="utf-8")

    print(f"Wrote HTML under {root}")
    # The keeper homepage isn't a ClickUp export, so refresh its chrome from the same tree.
    patch_chrome(root, tree, site_name)


def main() -> None:
    parser = argparse.ArgumentParser(description="Export a ClickUp Doc to local HTML.")
    parser.add_argument(
        "--out",
        default=str(Path(__file__).resolve().parent),
        help="Site root (default: this folder)",
    )
    parser.add_argument("--dry-run", action="store_true", help="Print the page tree without writing files")
    parser.add_argument(
        "--patch-nav",
        action="store_true",
        help="Rebuild styles and sidebar on already-exported HTML without calling ClickUp",
    )
    args = parser.parse_args()
    root = Path(args.out).resolve()
    if args.patch_nav:
        tree = load_nav(root)
        write_shared_assets(root, tree)
        patch_chrome(root, tree)
        return
    write_site(root, args.dry_run)


if __name__ == "__main__":
    main()
