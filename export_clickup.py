def href_from(rel: Path, target: str) -> str:
    start = Path(".") if rel == Path(".") else rel
    href = os.path.relpath(target, start).replace("\\", "/")
    if href == ".":
        return "index.html" if target.endswith(".html") else "./"
    if target.endswith("/") and not href.endswith(("/", ".html")):
        href += "/"
    return href


def site_key(rel: Path) -> str:
    """Root-relative key used to match a page against the nav tree."""
    if rel in (Path("."), Path("")):
        return "index.html"
    return rel.as_posix() + "/"


def nav_items(tree: list[dict], rel: Path, current: str) -> str:
    def contains_current(node: dict) -> bool:
        if node["href"] == current:
            return True
        return any(contains_current(kid) for kid in node.get("children") or [])

    def render(nodes: list[dict], depth: int) -> str:
        out = []
        for node in nodes:
            kids = node.get("children") or []
            active = node["href"] == current
            branch = contains_current(node)
            classes = ["nav-node"]
            if kids:
                classes.append("has-kids")
            if branch:
                classes.append("is-branch")
            label = esc(node["label"])
            link = (
                f'<a class="nav-link" href="{href_from(rel, node["href"])}" title="{label}"'
                + (' aria-current="page"' if active else "")
                + f">{label}</a>"
            )
            if not kids:
                out.append(f'<li class="{" ".join(classes)}">{link}</li>')
                continue
            open_state = "true" if branch else "false"
            caret = (
                f'<button class="nav-caret" type="button" aria-expanded="{open_state}"'
                f' aria-label="Toggle {esc(node["label"])}"></button>'
            )
            out.append(
                f'<li class="{" ".join(classes)}" data-key="{esc(node["href"])}" data-open="{open_state}">'
                f'<div class="nav-row">{link}{caret}</div>'
                f'<ul class="nav-list nav-sub">{render(kids, depth + 1)}</ul>'
                "</li>"
            )
        return "".join(out)

    return render(tree, 0)


